import json,sys,pathlib
URL=(pathlib.Path(__file__).resolve().parent.parent/'index.html').as_uri()
from playwright.sync_api import sync_playwright
R=[];errs=[]
def t(n,ok):R.append((n,bool(ok)))
with sync_playwright() as p:
    b=p.chromium.launch();c=b.new_context(viewport={'width':390,'height':844},device_scale_factor=2,permissions=[],color_scheme='light')
    pg=c.new_page();pg.on('pageerror',lambda e:errs.append(str(e)));pg.on('console',lambda m:m.type=='error' and errs.append(m.text))
    pg.goto(URL)
    t('Página carrega com título e idioma pt-BR',pg.title()=='EcoPonto GO' and pg.get_attribute('html','lang')=='pt-BR')
    t('7 categorias de materiais exibidas',pg.locator('.tile').count()==7)
    pg.screenshot(path='s1.png')
    pg.fill('#q','pet');t('Busca "pet" retorna Garrafa PET',pg.locator('#res li').count()>=1 and 'Garrafa PET' in pg.inner_text('#res'))
    pg.fill('#q','pilha');t('Busca "pilha" sem acento/caixa retorna resultado',pg.locator('#res li').count()>=1)
    pg.fill('#q','xyzabc');t('Busca sem resultado mostra mensagem',  'Nada encontrado' in pg.inner_text('#res'))
    pg.fill('#q','');pg.click('.tile[data-k=vidro]');t('Categoria abre guia com "Pode/Não pode"',pg.is_visible('#dlg') and 'Não pode' in pg.inner_text('#dlg'))
    pg.screenshot(path='s2.png');pg.keyboard.press('Escape');t('Tecla Esc fecha o guia',not pg.is_visible('#dlg'))
    pg.click('nav button[data-v=map]');t('Mapa exibe 8 pontos',pg.locator('.pt').count()==8)
    pg.click('#fl .chip[data-f=oleo]');n=pg.locator('.pt').count();t('Filtro "Óleo" reduz a lista',0<n<8)
    pg.click('#fl .chip[data-f=todos]');pg.locator('.pin').first.focus();pg.keyboard.press('Enter');t('Pino acessível por teclado seleciona ponto',pg.locator('.pt[data-on]').count()==1)
    t('Lista ordenada por distância',(lambda d:d==sorted(d))([float(x.split()[0]) for x in pg.locator('.pt .tag').all_inner_texts()]))
    pg.screenshot(path='s3.png')
    pg.click('nav button[data-v=set]');pg.check('#s-lg');pg.check('#s-hc')
    t('Texto maior aplica classe e escala fonte',pg.evaluate("getComputedStyle(document.documentElement).fontSize")=='20px')
    t('Alto contraste aplica classe',pg.evaluate("document.documentElement.classList.contains('hc')"))
    pg.screenshot(path='s4.png')
    pg.reload();t('Preferências persistem após recarregar',pg.evaluate("document.documentElement.classList.contains('lg')"))
    bad=pg.evaluate("[...document.querySelectorAll('button,input,select,a.btn')].filter(e=>e.offsetParent&&!(e.getAttribute('aria-label')||e.textContent.trim()||e.labels&&e.labels.length)).length");t('Controles com nome acessível',bad==0)
    t('Sem erros de JavaScript no console',not errs)
    c2=b.new_context(viewport={'width':390,'height':844},color_scheme='dark');q=c2.new_page();q.goto(URL)
    t('Tema escuro automático (prefers-color-scheme)',q.evaluate("getComputedStyle(document.body).backgroundColor")=='rgb(15, 22, 18)');q.screenshot(path='s5.png')
    c3=b.new_context(viewport={'width':320,'height':640});w=c3.new_page();w.goto(URL)
    t('Sem rolagem horizontal em 320 px',w.evaluate("document.documentElement.scrollWidth<=320"))
    b.close()
json.dump(R,open('tests.json','w'),ensure_ascii=False);print(R);print(errs)
